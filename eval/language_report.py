"""Analyse a run of the language-ability check (train/S8_语言能力检查.ipynb) from its per-item files.

  python -m eval.language_report runs/<UTC>_s8_language_check      # writes analysis.md into that folder

The notebook's own report.md gives the headline numbers per model. This adds what needs the per-item answers:

1. scheduling self-check against each student's own teacher. The notebook that produced the first run scored
   every model against the paper formula's optimum, which is the wrong target for the PS-teacher students
2. which option letter each model picks on the multiple-choice questions
3. each student against the base of the same size on the same MMLU questions (exact McNemar test)
"""
import argparse
import contextlib
import io
import json
import math
import os

from deploy.wire import state_from_dict
from sim.cost import best_action, ps_costs

NOTEBOOK = os.path.join("train", "S8_语言能力检查.ipynb")
ORDER = ["base_0.5b", "main_0.5b", "ps_0.5b", "base_1.5b", "soft_1.5b", "hard_1.5b", "ps_soft_1.5b", "ps_hard_1.5b"]
NAMES = {"base_0.5b": "untrained 0.5B", "main_0.5b": "0.5B, paper teacher (deployed)", "ps_0.5b": "0.5B, PS teacher",
         "base_1.5b": "untrained 1.5B", "soft_1.5b": "1.5B soft labels, paper teacher",
         "hard_1.5b": "1.5B hard labels, paper teacher", "ps_soft_1.5b": "1.5B soft labels, PS teacher",
         "ps_hard_1.5b": "1.5B hard labels, PS teacher"}


def notebook_data():
    """The built-in data cell of the notebook, executed: scheduling examples and helper functions."""
    with open(NOTEBOOK, encoding="utf-8") as f:
        nb = json.load(f)
    code = ["".join(c["source"]) for c in nb["cells"] if c["cell_type"] == "code"]
    ns = {}
    with contextlib.redirect_stdout(io.StringIO()):
        exec(compile(code[3], "notebook cell 4", "exec"), ns)
    return ns


def base_of(key):
    return "base_0.5b" if "0.5b" in key else "base_1.5b"


def mcnemar(a, b):
    """Paired right/wrong lists -> (a right and b wrong, a wrong and b right, exact two-sided p on those pairs)."""
    n01 = sum(1 for x, y in zip(a, b) if x and not y)
    n10 = sum(1 for x, y in zip(a, b) if not x and y)
    n = n01 + n10
    if n == 0:
        return n01, n10, 1.0
    tail = sum(math.comb(n, i) for i in range(min(n01, n10) + 1)) / 2 ** n
    return n01, n10, min(1.0, 2 * tail)


def load(run_dir):
    models, items = {}, {}
    for k in ORDER:
        mp, ip = os.path.join(run_dir, f"model_{k}.json"), os.path.join(run_dir, f"items_{k}.json")
        if os.path.exists(mp) and os.path.exists(ip):
            with open(mp, encoding="utf-8") as f:
                models[k] = json.load(f)
            with open(ip, encoding="utf-8") as f:
                items[k] = json.load(f)
    return models, items


def self_check(items, sched):
    """Per model: (hits against the paper optimum, hits against the PS optimum, number of examples)."""
    paper = [ex["best"] for ex in sched]
    ps = [best_action(ps_costs(state_from_dict(ex["state"]))) for ex in sched]
    out = {}
    for k, it in items.items():
        preds = [x["pred"] for x in it["sched"]]
        assert len(preds) == len(sched)
        out[k] = (sum(p == b for p, b in zip(preds, paper)), sum(p == b for p, b in zip(preds, ps)), len(preds))
    return out


def analysis(models, items, sched):
    keys = [k for k in ORDER if k in models]
    check = self_check(items, sched)
    lines = ["# Language-ability check: analysis of the per-item answers", "",
             "Generated by `python -m eval.language_report`. Colab, merged LoRA, "
             f"{models[keys[0]]['dtype']} on {models[keys[0]]['gpu']}.", "",
             "## Headline numbers", "",
             "Perplexity: lower is better; in brackets the student divided by the base of the same size. "
             "Chat: 20 ordinary questions per system prompt, counted when the whole answer is one action letter.", "",
             "| Model | wikitext-2 perplexity | built-in perplexity zh / en | chat answers that are one letter (default / scheduler system prompt) | MMLU by option letter | MMLU by option text |",
             "|---|---|---|---|---|---|"]
    for k in keys:
        r, b = models[k], models[base_of(k)]
        w = r["ppl"]["wikitext"]
        ratio = "" if k == base_of(k) or not w else f" (×{w['ppl'] / b['ppl']['wikitext']['ppl']:.2f})"
        m = r["mcq"]["mmlu"]
        lines.append(f"| {NAMES[k]} | {w['ppl']:.1f}{ratio} | {r['ppl']['zh']['ppl']:.1f} / {r['ppl']['en']['ppl']:.1f} | "
                     f"{r['chat']['default']['letter']}/{r['chat']['default']['n']} · "
                     f"{r['chat']['scheduler']['letter']}/{r['chat']['scheduler']['n']} | "
                     f"{100 * m['letter_acc']:.1f}% | {100 * m['cloze_acc']:.1f}% |")
    lines += ["", "## Scheduling self-check against each student's own teacher", "",
              "Eight scheduling prompts; the answer is the most likely legal letter. The paper-teacher students are "
              "scored against the paper formula's optimum and the PS-teacher students against the PS-aware formula's. "
              "On three of the eight states the PS formula's best and second-best server are within 0.02 slots.", "",
              "| Model | Against the paper optimum | Against the PS optimum | Probability mass on action letters |", "|---|---|---|---|"]
    for k in keys:
        p, s, n = check[k]
        lines.append(f"| {NAMES[k]} | {p}/{n} | {s}/{n} | {models[k]['sched']['letter_mass']:.3f} |")
    lines += ["", "## Which option letter is picked", "",
              "Counts of A / B / C / D picked on the 200 MMLU questions; the correct answers are "
              + " / ".join(str(sum(1 for r in items[keys[0]]["mcq"]["mmlu"] if r["answer"] == i)) for i in range(4))
              + ". In the scheduling prompt A means local execution and B means server 1.", "",
              "| Model | A | B | C | D |", "|---|---|---|---|---|"]
    for k in keys:
        c = [sum(1 for r in items[k]["mcq"]["mmlu"] if r["letter_pred"] == i) for i in range(4)]
        lines.append(f"| {NAMES[k]} | " + " | ".join(str(x) for x in c) + " |")
    lines += ["", "## Each student against the base of the same size, same 200 MMLU questions", "",
              "Pairs where only one of the two is right, and the exact two-sided McNemar p-value.", "",
              "| Student | Reading | Base | Student | Base right, student wrong | Base wrong, student right | p |",
              "|---|---|---|---|---|---|---|"]
    for k in keys:
        if k == base_of(k):
            continue
        base, st = items[base_of(k)]["mcq"]["mmlu"], items[k]["mcq"]["mmlu"]
        assert [r["answer"] for r in base] == [r["answer"] for r in st]
        for field, name in (("letter_pred", "option letter"), ("cloze_pred", "option text")):
            a = [r[field] == r["answer"] for r in base]
            b = [r[field] == r["answer"] for r in st]
            n01, n10, p = mcnemar(a, b)
            lines.append(f"| {NAMES[k]} | {name} | {100 * sum(a) / len(a):.1f}% | {100 * sum(b) / len(b):.1f}% | {n01} | {n10} | "
                         f"{p:.4f} |")
    lines += ["", "The built-in sets are small (16 passages, 20 chat questions, 32 multiple-choice questions) and MMLU is a "
              "random 200 of its test set, so only large changes show. Chat answers are classified by form, not checked "
              "for correctness."]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("run_dir")
    args = ap.parse_args()
    models, items = load(args.run_dir)
    text = analysis(models, items, notebook_data()["SCHED"])
    path = os.path.join(args.run_dir, "analysis.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print(text)
    print("wrote", path)


if __name__ == "__main__":
    main()
