# ===== 第 3 段：由上面推出来的处理速率 =====
def mbits_per_slot(ghz):
    """频率 ghz 的 CPU 一个时间槽能处理多少 Mbits。
    例：41.8 GHz × 0.1 s ÷ 0.297 G周期/Mbit ≈ 14.07 Mbits/槽。"""
    return ghz * SLOT_S / GCYCLES_PER_MBIT


